class Maze {
private:
    vector<vector<int>> grid;
public:
    Maze() {}
    void updateGrid(const vector<vector<int>>& newGrid) { if (!newGrid.empty()) grid = newGrid; }
    const vector<vector<int>>& getGrid() const { return grid; }
    void render(sf::RenderWindow& window, sf::Texture& wallTexture, sf::Texture& doorTexture) {
        if (grid.empty()) return;
        sf::Sprite tile(wallTexture); sf::Sprite door(doorTexture);
        sf::RectangleShape floorRect({ 41.f, 41.f }); floorRect.setFillColor(sf::Color::Black);
        float wSX = 40.5f / wallTexture.getSize().x, wSY = 40.5f / wallTexture.getSize().y;
        float dSX = (40.0f * 1.5f) / doorTexture.getSize().x, dSY = (40.0f * 1.5f) / doorTexture.getSize().y;
        for (int r = 0; r < (int)grid.size(); r++) {
            for (int c = 0; c < (int)grid[r].size(); c++) {
                float x = c * 40.f, y = r * 40.f;
                if (grid[r][c] == 1) { tile.setScale({ wSX, wSY }); tile.setPosition({ x, y }); window.draw(tile); }
                else if (grid[r][c] == 2) { 
                    door.setOrigin({ (float)doorTexture.getSize().x / 2.f, (float)doorTexture.getSize().y / 2.f });
                    door.setScale({ dSX, dSY }); door.setPosition({ x + 20.f, y + 20.f }); window.draw(door); 
                } else { floorRect.setPosition({ x, y }); window.draw(floorRect); }
            }
        }
    }
    bool isWall(const sf::Vector2f& pos) {
        if (grid.empty()) return true;
        int c = (int)(pos.x / 40.f), r = (int)(pos.y / 40.f);
        if (r < 0 || r >= (int)grid.size() || (grid.size() > 0 && (c < 0 || c >= (int)grid[0].size()))) return true;
        return grid[r][c] == 1;
    }
    bool isGoal(sf::Vector2f pos) {
        if (grid.empty()) return false;
        int c = (int)(pos.x / 40.f), r = (int)(pos.y / 40.f);
        if (r < 0 || r >= (int)grid.size() || (grid.size() > 0 && (c < 0 || c >= (int)grid[0].size()))) return false;
        return grid[r][c] == 2;
    }
    vector<vector<int>> getDistanceMap(sf::Vector2f targetPos) {
        if (grid.empty()) return {};
        int tC = (int)(targetPos.x / 40.f), tR = (int)(targetPos.y / 40.f);
        std::vector<std::vector<int>> distMap(grid.size(), std::vector<int>(grid[0].size(), -1));
        std::queue<sf::Vector2i> q;
        if (tR >= 0 && tR < (int)grid.size() && tC >= 0 && tC < (int)grid[0].size()) { q.push({ tC, tR }); distMap[tR][tC] = 0; }
        int dR[] = { -1, 1, 0, 0 }, dC[] = { 0, 0, -1, 1 };
        while (!q.empty()) {
            sf::Vector2i curr = q.front(); q.pop();
            for (int i = 0; i < 4; i++) {
                int nR = curr.y + dR[i], nC = curr.x + dC[i];
                if (nR >= 0 && nR < (int)grid.size() && nC >= 0 && nC < (int)grid[0].size()) {
                    if (grid[nR][nC] != 1 && distMap[nR][nC] == -1) { distMap[nR][nC] = distMap[curr.y][curr.x] + 1; q.push({ nC, nR }); }
                }
            }
        }
        return distMap;
    }
};

