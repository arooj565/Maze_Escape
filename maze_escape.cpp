class Player {
public:
    sf::Vector2f position; std::optional<sf::Sprite> body;
    void init(sf::Vector2f sP, const sf::Texture& tex) {
        body.emplace(tex); position = sP; sf::FloatRect b = body->getLocalBounds();
        body->setOrigin({ b.size.x/2.f, b.size.y/2.f });
        if (b.size.x!=0) body->setScale({ 40.f/b.size.x, 40.f/b.size.y }); body->setPosition(position);
    }
    void update(float dt, Maze& maze) {
        sf::Vector2f m(0,0);
        if (sf::Keyboard::isKeyPressed(sf::Keyboard::Key::Up)) m.y-=1; if (sf::Keyboard::isKeyPressed(sf::Keyboard::Key::Down)) m.y+=1;
        if (sf::Keyboard::isKeyPressed(sf::Keyboard::Key::Left)) m.x-=1; if (sf::Keyboard::isKeyPressed(sf::Keyboard::Key::Right)) m.x+=1;
        if (m.x!=0 || m.y!=0) { float len=sqrt(m.x*m.x+m.y*m.y); m/=len; }
        sf::Vector2f n = position + m * 180.f * dt;
        float r = 14.f; // Collision radius
        auto cw = [&](sf::Vector2f p) {
            return maze.isWall({p.x-r,p.y-r}) || maze.isWall({p.x+r,p.y-r}) || maze.isWall({p.x-r,p.y+r}) || maze.isWall({p.x+r,p.y+r});
        };
        if (!cw({n.x, position.y})) position.x = n.x;
        if (!cw({position.x, n.y})) position.y = n.y;
        if (body) body->setPosition(position);
    }
};

